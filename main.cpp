#include <string>
#include <vector>

void alternate_sum() {
    int acc = 0;
    for (int i = 1; i <= 12; ++i) {
        if (i % 2 == 0) acc += i; else acc -= i;
    }
    (void)acc;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void count_down() {
    int acc = 0;
    for (int i = 8; i > 0; --i) acc += i;
    (void)acc;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

extern "C" int quiet_summit();
extern "C" void radiant_beacon();
extern "C" void gentle_haven();

int main() {
    alternate_sum();
    least_multiple();
    count_down();
    collect_triples();
    radiant_beacon();
    gentle_haven();
    return quiet_summit();
}
